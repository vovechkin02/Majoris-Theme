#!/usr/bin/env python3
"""Translate prototype semantic tokens into scoped St CSS; never GTK CSS."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generate():
    tokens = json.loads((ROOT / 'theme/tokens.json').read_text())
    rules = ['/* Generated by login/scripts/generate-theme.py. SPDX-License-Identifier: MIT */']
    for variant, t in tokens.items():
        root = f'.majoris-login.majoris-{variant}'
        panel = f'#panel.majoris-login-panel.majoris-{variant}'
        menu = f'.majoris-login-menu.majoris-{variant}'

        def rule(selectors, declarations):
            rules.append(',\n'.join(selectors) + ' { ' + declarations + ' }')

        # St accepts one Pango family, not a browser CSS family list. Pango and
        # the system fontconfig configuration supply missing-glyph fallbacks.
        rule([root, panel, menu], f'font-family: "Plus Jakarta Sans"; font-size: 13px; color: {t["text"]};')
        rule([f'{root} StLabel', f'{root} StIcon', f'{panel} StLabel', f'{panel} StIcon', f'{menu} StLabel', f'{menu} StIcon'], f'color: {t["text"]};')
        rule([f'{root} .majoris-card'], f'width: 350px; padding: 36px 40px 28px; border-radius: 8px; border: 1px solid {t["card-border"]}; background-color: {t["card"]}; box-shadow: 0 24px 72px {t["shadow"]}; spacing: 8px;')
        rule([f'{root} .login-dialog-user-selection-box'], 'spacing: 16px;')
        rule([f'{root} .login-dialog-user-list-view'], 'max-height: 320px;')
        rule([f'{root} .login-dialog-user-list'], 'spacing: 8px; width: 350px;')
        rule([f'{root} .login-dialog-user-list-item'], f'padding: 10px; border: 1px solid transparent; border-radius: 8px; background-color: {t["field"]};')
        rule([f'{root} .login-dialog-user-list-item:hover', f'{root} .login-dialog-user-list-item:selected'], f'background-color: {t["control-hover"]}; border-color: {t["field-border"]};')
        rule([f'{root} .user-widget.vertical'], 'spacing: 20px; padding: 0;')
        rule([f'{root} .user-widget.vertical .user-widget-label', f'{root} .majoris-heading'], 'font-size: 25px; font-weight: 700; text-align: center;')
        rule([f'{root} .user-widget.horizontal .user-widget-label'], 'font-size: 13px; font-weight: 600;')
        rule([f'{root} .user-icon'], f'icon-size: 72px; border-radius: 999px; border: 2px solid rgba(255,255,255,.55); background-gradient-direction: vertical; background-gradient-start: {t["avatar-a"]}; background-gradient-end: {t["avatar-b"]};')
        rule([f'{root} .user-widget.horizontal .user-icon'], 'icon-size: 42px;')
        rule([f'{root} .majoris-avatar-initials'], 'font-size: 23px; font-weight: 700; color: #FFFFFF;')
        rule([f'{root} .user-widget.horizontal .majoris-avatar-initials'], 'font-size: 12px;')
        rule([f'{root} .majoris-question'], 'font-size: 12px; font-weight: 600;')
        rule([f'{root} .majoris-intro'], f'font-size: 13px; color: {t["muted"]}; padding-bottom: 8px;')
        rule([f'{root} .login-dialog-button-box'], 'spacing: 0; width: 350px;')
        rule([f'{root} .login-dialog-prompt-entry'], f'height: 46px; min-height: 46px; padding: 0 14px; border: 1px solid {t["field-border"]}; border-radius: 8px; background-color: {t["field"]}; color: {t["text"]}; selection-background-color: #6366F1; selected-color: #FFFFFF; transition-duration: 128ms;')
        rule([f'{root} .login-dialog-prompt-entry:hover'], f'background-color: {t["field-hover"]};')
        rule([f'{root} .login-dialog-prompt-entry:focus'], 'border-color: #6366F1; box-shadow: 0 0 0 2px rgba(99,102,241,.21);')
        rule([f'{root} .login-dialog-prompt-entry:insensitive'], f'color: {t["muted"]}; background-color: {t["field"]};')
        rule([f'{root} .login-dialog-prompt-entry StLabel'], f'color: {t["faint"]};')
        rule([f'{root} .login-dialog-message'], f'height: 26px; min-height: 26px; font-size: 11px; text-align: left; color: {t["muted"]}; padding: 0;')
        rule([f'{root} .login-dialog-message-warning'], 'color: ' + ('#a32939;' if variant == 'light' else '#ffc2c2;'))
        rule([f'{root} .majoris-primary'], 'height: 46px; padding: 0; border: 1px solid transparent; border-radius: 8px; background-color: #6366F1; color: #FFFFFF; font-size: 13px; font-weight: 700; transition-duration: 128ms;')
        rule([f'{root} .majoris-primary StLabel', f'{root} .majoris-primary StIcon'], 'color: #FFFFFF;')
        rule([f'{root} .majoris-primary StBoxLayout'], 'spacing: 12px;')
        rule([f'{root} .majoris-primary:hover'], 'background-color: #7578FA;')
        rule([f'{root} .majoris-primary:active'], 'background-color: #5558DA;')
        rule([f'{root} .majoris-primary:insensitive'], f'background-color: {t["control-active"]}; color: {t["muted"]};')
        rule([f'{root} .majoris-primary:insensitive StLabel', f'{root} .majoris-primary:insensitive StIcon'], f'color: {t["muted"]};')
        rule([f'{root} .majoris-auth-footer'], 'padding-top: 22px; spacing: 16px;')
        rule([f'{root} .majoris-text-action', f'{root} .login-dialog-session-list-button', f'{root} .login-dialog-not-listed-button'], f'background-color: transparent; color: {t["muted"]}; border-radius: 8px; padding: 6px 3px; font-size: 12px; font-weight: 600;')
        rule([f'{root} .majoris-text-action StLabel', f'{root} .login-dialog-session-list-button StLabel'], f'color: {t["muted"]};')
        rule([f'{root} .majoris-text-action:hover', f'{root} .login-dialog-session-list-button:hover', f'{root} .login-dialog-not-listed-button:hover'], f'background-color: {t["control-hover"]}; color: {t["text"]};')
        rule([f'{root} .majoris-header'], 'spacing: 16px;')
        rule([f'{root} .majoris-brand'], 'spacing: 12px; font-size: 21px; font-weight: 700;')
        rule([f'{root} .majoris-top-date', f'{root} .majoris-caption'], f'color: {t["muted"]}; font-size: 13px;')
        rule([f'{root} .majoris-caption'], 'font-size: 11px;')
        rule([f'{root} .unlock-dialog-clock'], 'spacing: 8px;')
        rule([f'{root} .unlock-dialog-clock-time'], 'font-size: 164px; font-weight: 500;')
        rule([f'{root} .unlock-dialog-clock-date'], f'font-size: 25px; color: {t["muted"]};')
        rule([f'{root} .unlock-dialog-clock-hint'], f'margin-top: 64px; padding: 12px 18px; border-radius: 8px; background-color: {t["card"]}; border: 1px solid {t["card-border"]}; font-size: 12px;')
        rule([panel], 'height: 36px; background-color: transparent; box-shadow: none; border: none; padding: 0 48px;')
        rule([f'{panel} .panel-button'], 'border-radius: 8px; -natural-hpadding: 9px; -minimum-hpadding: 7px; transition-duration: 128ms;')
        rule([f'{panel} .panel-button:hover', f'{panel} .panel-button:checked'], f'background-color: {t["control-hover"]};')
        rule([f'{panel} .panel-button:active'], f'background-color: {t["control-active"]};')
        rule([f'{panel} .panel-button:insensitive', f'{panel} .panel-button:insensitive StIcon', f'{menu} .popup-menu-item:insensitive StLabel', f'{menu} .popup-menu-item:insensitive StIcon'], f'color: {t["faint"]};')
        rule([f'{panel} .system-status-icon'], 'icon-size: 18px;')
        rule([menu], f'-arrow-background-color: {t["popover"]}; -arrow-border-color: {t["card-border"]}; -arrow-border-width: 1px; -arrow-border-radius: 8px; -arrow-rise: 0px; -boxpointer-gap: 8px;')
        rule([f'{menu} .popup-menu-content', f'{menu} .quick-settings', f'{menu} .quick-toggle-menu'], f'background-color: {t["popover"]}; border-radius: 8px; border: 1px solid {t["card-border"]}; box-shadow: 0 14px 40px {t["shadow"]}; padding: 8px;')
        rule([f'{menu} .popup-menu-item'], f'color: {t["text"]}; border-radius: 8px; padding: 12px;')
        rule([f'{menu} .popup-menu-item:hover', f'{menu} .popup-menu-item:active'], f'background-color: {t["control-hover"]};')
        rule([f'{menu} .quick-toggle', f'{menu} .icon-button'], f'background-color: {t["field"]}; border-radius: 8px; color: {t["text"]};')
        rule([f'{menu} .quick-toggle:hover', f'{menu} .icon-button:hover'], f'background-color: {t["control-hover"]};')
        rule([f'{menu} .quick-toggle:active', f'{menu} .icon-button:active'], f'background-color: {t["control-active"]};')
        rule([f'{menu} .quick-toggle:checked', f'{menu} .popup-menu-item:checked'], 'background-color: #6366F1; color: #FFFFFF;')
        rule([f'{menu} .quick-toggle:checked StLabel', f'{menu} .quick-toggle:checked StIcon', f'{menu} .popup-menu-item:checked StLabel', f'{menu} .popup-menu-item:checked StIcon'], 'color: #FFFFFF;')
        rule([f'{menu} .quick-toggle:insensitive', f'{menu} .quick-toggle:insensitive StLabel', f'{menu} .quick-toggle:insensitive StIcon', f'{menu} .icon-button:insensitive', f'{menu} .icon-button:insensitive StIcon'], f'background-color: {t["field"]}; color: {t["faint"]};')
        rule([f'{root} StButton:focus', f'{panel} .panel-button:focus', f'{menu} .popup-menu-item:focus'], 'box-shadow: inset 0 0 0 2px #6366F1;')
        # Respect GNOME high contrast in both private screen roots and detached menus.
        rule([f'{root}.majoris-high-contrast .majoris-card', f'{menu}.majoris-high-contrast .popup-menu-content'], 'background-color: ' + ('#FFFFFF; color: #000000; border-color: #000000;' if variant == 'light' else '#000000; color: #FFFFFF; border-color: #FFFFFF;'))
    return '\n\n'.join(rules) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'theme/login.css'
    text = generate()
    if args.check:
        assert target.read_text() == text, 'Login CSS drift; regenerate'
    else:
        target.write_text(text)
